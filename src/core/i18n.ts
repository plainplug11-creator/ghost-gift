const dicts = { ru, en, uk } as const;
export type Lang = keyof typeof dicts;

const qs = new URLSearchParams(location.search).get('lang');
const code = tg.user.language_code ?? '';
export const lang: Lang =
  qs === 'en' || qs === 'ru' || qs === 'uk' ? qs : code.startsWith('uk') ? 'uk' : code.startsWith('en') ? 'en' : 'ru';
document.documentElement.lang = lang;

export function t(key: I18nKey, params?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? ru[key];
  if (params) for (const k in params) s = s.replace(`{${k}}`, String(params[k]));
  return s;
}

const nf = new Intl.NumberFormat(lang === 'en' ? 'en-US' : lang === 'uk' ? 'uk-UA' : 'ru-RU');
export const fmt = (n: number) => nf.format(Math.round(n));

export function greeting(d = new Date()): string {
  const h = d.getHours();
  return t(h < 5 ? 'greet.night' : h < 12 ? 'greet.morning' : h < 18 ? 'greet.day' : h < 23 ? 'greet.evening' : 'greet.night');
}
